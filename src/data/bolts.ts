import type { BoltDef } from "./types";

/** Porcas das 4 rodas dispostas em circulo no plano YZ. */
function porcasRoda(
  prefixo: string,
  parte: string,
  x: number,
  z: number,
  dir: 1 | -1
): BoltDef[] {
  const r = 0.095;
  return [0, 1, 2, 3].map((i) => {
    const a = (i / 4) * Math.PI * 2 + Math.PI / 4;
    return {
      id: `${prefixo}-${i + 1}`,
      label: `Porca da roda ${i + 1}`,
      parte,
      tipo: "porca" as const,
      medida: 19,
      torque: 110,
      pos: [x, 0.34 + Math.sin(a) * r, z + Math.cos(a) * r] as [
        number,
        number,
        number
      ],
      eixo: [dir, 0, 0] as [number, number, number],
      comprimento: 0.05,
    };
  });
}

