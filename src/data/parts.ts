/** Pecas de um sistema, na ordem em que a forca as atravessa. */
export function cadeiaDoSistema(sistema: string): PartDef[] {
  return PARTES.filter((p) => p.sistema === sistema).sort((a, b) => (a.elo ?? 99) - (b.elo ?? 99))
}

/** Posicao de um slot da bancada de trabalho. */
export const COLUNAS_BANCADA = 8
export const SLOTS_BANCADA = 40

export function slotBancada(i: number): [number, number, number] {
  const col = i % COLUNAS_BANCADA
  const row = Math.floor(i / COLUNAS_BANCADA)
  return [2.44 + row * 0.3, 0.96, -1.02 + col * 0.29]
}
