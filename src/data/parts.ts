/** Componentes que dependem de `id` estar instalado (inverso de `requer`). */
export const DEPENDENTES: Record<string, string[]> = (() => {
  const m: Record<string, string[]> = {}
  for (const p of PARTES) m[p.id] = []
  for (const p of PARTES) for (const r of p.requer) m[r]?.push(p.id)
  return m
})()

